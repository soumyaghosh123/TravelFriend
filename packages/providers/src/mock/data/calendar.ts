type Row = [priceIndex: number, maxC: number, minC: number, summary: string];

function months(rows: Row[]): MonthClimate[] {
  return rows.map(([priceIndex, maxC, minC, summary], i) => ({
    month: i + 1,
    priceIndex,
    maxC,
    minC,
    summary,
  }));
}

